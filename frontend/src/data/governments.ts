export const ENABLED_GOVERNMENTS = GOVERNMENTS.filter(g => g.isEnabled);

export const STATE_GOVERNMENTS = GOVERNMENTS.filter(g => g.jurisdictionType === 'state');

export const UNION_TERRITORIES = GOVERNMENTS.filter(g => g.jurisdictionType === 'union-territory');

export const CENTRAL_GOVERNMENT = GOVERNMENTS.find(g => g.jurisdictionType === 'central')!;

export function getAllGovernments(): GovernmentConfig[] {
  return ENABLED_GOVERNMENTS;
}

export function getAllStates(): GovernmentConfig[] {
  return STATE_GOVERNMENTS;
}

export function getAllUnionTerritories(): GovernmentConfig[] {
  return UNION_TERRITORIES;
}

export function getGovernmentBySlug(slug: string): GovernmentConfig | undefined {
  return GOVERNMENTS.find(g => g.slug.toLowerCase() === slug.toLowerCase());
}

export function getGovernmentById(id: string): GovernmentConfig | undefined {
  return GOVERNMENTS.find(g => g.id.toLowerCase() === id.toLowerCase());
}

export function getGovernmentByCode(code: string): GovernmentConfig | undefined {
  return GOVERNMENTS.find(g => g.stateCode?.toUpperCase() === code.toUpperCase());
}

export function getGovernmentByStateCode(stateCode: string): GovernmentConfig | undefined {
  return getGovernmentByCode(stateCode);
}
